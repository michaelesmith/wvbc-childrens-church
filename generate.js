#!/usr/bin/env node
// Generate print-ready PDFs from lesson markdown files.
//
//   node generate.js                      # all lessons
//   node generate.js 2026-10-18 lessons/2026-10-11.md   # only these
//   node generate.js --regen              # overwrite existing PDFs (or --regenerate)
//
// Draft lessons (draft: true) are never generated and are reported as errors.
// Existing PDFs are skipped unless --regen is passed.
// Every run also refreshes the schedule table in README.md from plans.csv.
//
// Each lesson is scaled to fill exactly two Letter pages, with the date and
// leaders in the page header and a small last week / next week recap.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";
import { marked } from "marked";
import puppeteer from "puppeteer";
import { PDFDocument } from "pdf-lib";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const LESSONS_DIR = path.join(ROOT, "lessons");
const OUTPUT_DIR = path.join(ROOT, "output");
const PLANS_CSV = path.join(ROOT, "plans.csv");
const README = path.join(ROOT, "README.md");
const SCHEDULE_START = "<!-- schedule:start (generated by generate.js) -->";
const SCHEDULE_END = "<!-- schedule:end -->";

const MAX_PAGES = 2;
const MIN_FONT_PT = 7;
const MAX_FONT_PT = 13;
const FONT_STEP_PT = 0.25;

const escapeHtml = (s) =>
  String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

// gray-matter parses YAML dates as UTC midnight; keep them as YYYY-MM-DD.
const isoDate = (d) => (d instanceof Date ? d.toISOString().slice(0, 10) : String(d));

const formatDate = (iso) =>
  new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-US", {
    weekday: "long", year: "numeric", month: "long", day: "numeric", timeZone: "UTC",
  });

function section(body, name) {
  const match = body.match(new RegExp(`^###\\s+${name}\\s*$([\\s\\S]*?)(?=^#{1,3}\\s|(?![\\s\\S]))`, "m"));
  return match ? match[1].trim() : "";
}

const takeaways = (body) =>
  [...section(body, "Takeaways").matchAll(/^\s*[-*]\s+(.+)$/gm)].map((m) => m[1].trim());

async function loadLessons() {
  const files = (await fs.readdir(LESSONS_DIR)).filter((f) => f.endsWith(".md")).sort();
  const lessons = await Promise.all(
    files.map(async (file) => {
      const { data, content } = matter(await fs.readFile(path.join(LESSONS_DIR, file), "utf8"));
      return {
        file,
        data,
        content,
        date: isoDate(data.date ?? path.basename(file, ".md")),
        takeaways: takeaways(content),
        practice: section(content, "Put It in Practice"),
      };
    }),
  );
  return lessons.sort((a, b) => a.date.localeCompare(b.date));
}

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') field += text[++i];
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field || row.length) rows.push([...row, field]);
  return rows;
}

const cell = (s) => String(s ?? "").trim().replace(/\|/g, "\\|");

// USFM book codes used in bible.com URLs.
const BOOKS = {
  genesis: "GEN", exodus: "EXO", leviticus: "LEV", numbers: "NUM", deuteronomy: "DEU", joshua: "JOS",
  judges: "JDG", ruth: "RUT", "1 samuel": "1SA", "2 samuel": "2SA", "1 kings": "1KI", "2 kings": "2KI",
  "1 chronicles": "1CH", "2 chronicles": "2CH", ezra: "EZR", nehemiah: "NEH", esther: "EST", job: "JOB",
  psalm: "PSA", psalms: "PSA", proverbs: "PRO", ecclesiastes: "ECC", "song of songs": "SNG", isaiah: "ISA",
  jeremiah: "JER", lamentations: "LAM", ezekiel: "EZK", daniel: "DAN", hosea: "HOS", joel: "JOL", amos: "AMO",
  obadiah: "OBA", jonah: "JON", micah: "MIC", nahum: "NAM", habakkuk: "HAB", zephaniah: "ZEP", haggai: "HAG",
  zechariah: "ZEC", malachi: "MAL", matthew: "MAT", mark: "MRK", luke: "LUK", john: "JHN", acts: "ACT",
  romans: "ROM", "1 corinthians": "1CO", "2 corinthians": "2CO", galatians: "GAL", ephesians: "EPH",
  philippians: "PHP", colossians: "COL", "1 thessalonians": "1TH", "2 thessalonians": "2TH", "1 timothy": "1TI",
  "2 timothy": "2TI", titus: "TIT", philemon: "PHM", hebrews: "HEB", james: "JAS", "1 peter": "1PE",
  "2 peter": "2PE", "1 john": "1JN", "2 john": "2JN", "3 john": "3JN", jude: "JUD", revelation: "REV",
};

// "Matthew 16:13-20" -> [Matthew 16:13-20](https://www.bible.com/bible/111/MAT.16.13-20.NIV)
// bible.com can't show a range across chapters, so those link to the starting chapter.
function bibleLink(ref) {
  const m = ref.trim().replace(/\s*[–—-]\s*/g, "-").match(/^(.+?)\s+(\d+)(?::(\d+)(?:-(\d+)(?::(\d+))?)?)?$/);
  const book = m && BOOKS[m[1].toLowerCase()];
  if (!book) return cell(ref);
  const [, , chapter, verse, end, endVerse] = m;
  const verses = verse && !endVerse ? `.${verse}${end ? `-${end}` : ""}` : "";
  return `[${cell(ref)}](https://www.bible.com/bible/111/${book}.${chapter}${verses}.NIV)`;
}

const scriptureLinks = (scripture) => String(scripture ?? "").split(";").filter((s) => s.trim()).map(bibleLink).join("; ");

async function updateReadmeSchedule(lessons) {
  const plans = parseCsv(await fs.readFile(PLANS_CSV, "utf8")).filter((r) => /^\d{4}-\d{2}-\d{2}$/.test(r[0]));
  const byDate = new Map(lessons.map((l) => [l.date, l]));
  const rows = plans.map(([date, topic, scripture, leaders]) => {
    const lesson = byDate.get(date);
    const link = lesson ? `[${date}](lessons/${lesson.file})` : date;
    const status = !lesson ? "No lesson" : lesson.data.draft ? "Draft" : "Ready";
    return `| ${link} | ${cell(topic)} | ${scriptureLinks(scripture)} | ${cell(leaders)} | ${status} |`;
  });
  // Blank lines around the table keep the marker comments from merging into it.
  const table = [
    SCHEDULE_START,
    "",
    "| Date | Topic | Scripture | Leaders | Status |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
    SCHEDULE_END,
  ].join("\n");

  const readme = await fs.readFile(README, "utf8");
  const start = readme.indexOf(SCHEDULE_START);
  const end = readme.indexOf(SCHEDULE_END);
  const updated = start >= 0 && end > start
    ? readme.slice(0, start) + table + readme.slice(end + SCHEDULE_END.length)
    : `${readme.trimEnd()}\n\n## Schedule\n\n${table}\n`;
  if (updated !== readme) {
    await fs.writeFile(README, updated);
    console.log("README.md schedule updated");
  }
}

// Accepts dates ("2026-10-18"), file names, or paths.
function selectLessons(lessons, args) {
  if (args.length === 0) return { selected: lessons, errors: [] };
  const selected = [];
  const errors = [];
  for (const arg of args) {
    const key = path.basename(arg, ".md");
    const lesson = lessons.find((l) => path.basename(l.file, ".md") === key || l.date === key);
    if (lesson) selected.push(lesson);
    else errors.push(`No lesson found for "${arg}"`);
  }
  return { selected, errors };
}

function recapHtml(last, next) {
  const lastHtml = last
    ? `<div class="recap-col">
        <h4>Last Week · ${escapeHtml(formatDate(last.date))}</h4>
        <p><strong>Topic:</strong> ${escapeHtml(last.data.title)}</p>
        ${last.data.memoryVerse ? `<p><strong>Memory Verse:</strong> “${escapeHtml(last.data.memoryVerse)}” — ${escapeHtml(last.data.memoryVerseRef)}</p>` : ""}
        ${last.takeaways.length ? `<p><strong>Takeaways:</strong></p><ul>${last.takeaways.map((t) => `<li>${marked.parseInline(t)}</li>`).join("")}</ul>` : ""}
        ${last.practice ? `<p><strong>Put It in Practice:</strong> ${marked.parseInline(last.practice)}</p>` : ""}
      </div>`
    : "";
  const nextHtml = next
    ? `<div class="recap-col recap-next">
        <h4>Next Week · ${escapeHtml(formatDate(next.date))}</h4>
        <p><strong>Topic:</strong> ${escapeHtml(next.data.title)}</p>
      </div>`
    : "";
  return lastHtml || nextHtml ? `<section class="recap">${lastHtml}${nextHtml}</section>` : "";
}

function lessonHtml(lesson, last, next) {
  // Drop the Theme Specific section when it has no content.
  const content = lesson.content.replace(/^###\s+Theme Specific\s*$\s*(?=^###\s|(?![\s\S]))/m, "");
  const body = recapHtml(last, next) + marked.parse(content);
  return `<!doctype html>
<html><head><meta charset="utf-8"><title>${escapeHtml(lesson.data.title)}</title>
<style>
  :root { --font-size: 11pt; }
  html { font-size: var(--font-size); }
  body { margin: 0; font-family: "Helvetica Neue", Helvetica, Arial, sans-serif; line-height: 1.35; color: #111; }
  h1 { font-size: 1.6rem; margin: 0 0 0.4rem; line-height: 1.2; }
  h3 { font-size: 1.1rem; margin: 0.9rem 0 0.3rem; padding-bottom: 0.1rem; border-bottom: 1px solid #bbb; break-after: avoid; }
  h4 { font-size: 1rem; margin: 0.6rem 0 0.2rem; break-after: avoid; }
  p { margin: 0 0 0.45rem; }
  ul { margin: 0 0 0.45rem; padding-left: 1.3rem; }
  li { margin: 0 0 0.15rem; break-inside: avoid; }
  li > p { margin: 0; }
  em { color: #444; }

  .recap { display: flex; gap: 1rem; margin: 0 0 0.6rem; padding: 0.35rem 0.6rem;
           border: 1px solid #ccc; border-radius: 4px; background: #f5f5f5;
           font-size: 0.78rem; line-height: 1.25; break-inside: avoid; }
  .recap-col { flex: 2; }
  .recap-next { flex: 1; border-left: 1px solid #ccc; padding-left: 0.8rem; }
  .recap h4 { margin: 0 0 0.2rem; font-size: 0.85rem; text-transform: uppercase; letter-spacing: 0.03em; color: #555; }
  .recap p, .recap ul { margin: 0 0 0.15rem; }
  .recap li { margin: 0; }
</style></head>
<body>${body}</body></html>`;
}

function headerTemplate(lesson) {
  const leaders = lesson.data.leaders ? `Leaders: ${escapeHtml(lesson.data.leaders)}` : "";
  return `<div style="width:100%; margin:0 0.5in; font-size:9pt; font-family:Helvetica, Arial, sans-serif; color:#555;
                      display:flex; justify-content:space-between; border-bottom:1px solid #ccc; padding-bottom:3px;">
    <span>${escapeHtml(formatDate(lesson.date))}</span><span>${leaders}</span>
  </div>`;
}

const footerTemplate = `<div style="width:100%; text-align:center; font-size:8pt; font-family:Helvetica, Arial, sans-serif; color:#888;">
  Page <span class="pageNumber"></span> of <span class="totalPages"></span></div>`;

async function renderPdf(page, lesson, fontPt) {
  await page.evaluate((pt) => document.documentElement.style.setProperty("--font-size", `${pt}pt`), fontPt);
  return page.pdf({
    format: "Letter",
    printBackground: true,
    displayHeaderFooter: true,
    headerTemplate: headerTemplate(lesson),
    footerTemplate,
    margin: { top: "0.7in", bottom: "0.55in", left: "0.5in", right: "0.5in" },
  });
}

const pageCount = async (pdf) => (await PDFDocument.load(pdf)).getPageCount();

// Find the largest font size that still fits in MAX_PAGES.
async function fitToPages(page, lesson) {
  const steps = Math.round((MAX_FONT_PT - MIN_FONT_PT) / FONT_STEP_PT);
  let lo = 0, hi = steps, best = null;
  while (lo <= hi) {
    const mid = Math.floor((lo + hi) / 2);
    const fontPt = MIN_FONT_PT + mid * FONT_STEP_PT;
    const pdf = await renderPdf(page, lesson, fontPt);
    if ((await pageCount(pdf)) <= MAX_PAGES) {
      best = { pdf, fontPt };
      lo = mid + 1;
    } else {
      hi = mid - 1;
    }
  }
  if (best) return best;
  const pdf = await renderPdf(page, lesson, MIN_FONT_PT);
  return { pdf, fontPt: MIN_FONT_PT, overflow: await pageCount(pdf) };
}

async function main() {
  const args = process.argv.slice(2);
  const regen = args.some((a) => a === "--regen" || a === "--regenerate");
  const lessons = await loadLessons();
  await updateReadmeSchedule(lessons);
  const { selected, errors } = selectLessons(lessons, args.filter((a) => !a.startsWith("--")));
  await fs.mkdir(OUTPUT_DIR, { recursive: true });

  const outFile = (lesson) => path.join(OUTPUT_DIR, `${path.basename(lesson.file, ".md")}.pdf`);
  const exists = (file) => fs.access(file).then(() => true, () => false);

  const todo = [];
  const warnings = [];
  for (const lesson of selected) {
    if (lesson.data.draft) {
      errors.push(`${lesson.file} is still a draft — set draft: false to generate it`);
    } else if (!regen && (await exists(outFile(lesson)))) {
      console.log(`${path.relative(ROOT, outFile(lesson))} already exists — skipped (use --regen to overwrite)`);
    } else {
      todo.push(lesson);
    }
  }

  if (todo.length) {
    const browser = await puppeteer.launch();
    try {
      const page = await browser.newPage();
      for (const lesson of todo) {
        const i = lessons.indexOf(lesson);
        await page.setContent(lessonHtml(lesson, lessons[i - 1], lessons[i + 1]), { waitUntil: "load" });
        const { pdf, fontPt, overflow } = await fitToPages(page, lesson);
        await fs.writeFile(outFile(lesson), pdf);
        const note = overflow ? ` — WARNING: still ${overflow} pages at minimum size` : "";
        console.log(`${path.relative(ROOT, outFile(lesson))} (${fontPt}pt)${note}`);
        if (!String(lesson.data.leaders ?? "").trim()) {
          warnings.push(`${lesson.file} has no leaders — the page header will show only the date`);
        }
      }
    } finally {
      await browser.close();
    }
  }

  if (warnings.length) {
    console.warn(`\n${warnings.length} warning(s):`);
    for (const warning of warnings) console.warn(`  WARNING: ${warning}`);
  }

  if (errors.length) {
    console.error(`\n${errors.length} error(s):`);
    for (const err of errors) console.error(`  ERROR: ${err}`);
    process.exitCode = 1;
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
